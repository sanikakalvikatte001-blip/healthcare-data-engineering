-- =============================================================================
-- 00_account_setup.sql  (run once as SYSADMIN / SECURITYADMIN)
-- Roles, warehouses and databases for the UM prior-auth pipeline.
--   RAW        landing zone written only by ADF (LOADER role)
--   ANALYTICS  dbt-owned models (TRANSFORMER role), read by REPORTER
-- =============================================================================
USE ROLE SECURITYADMIN;
CREATE ROLE IF NOT EXISTS LOADER;        -- ADF service user
CREATE ROLE IF NOT EXISTS TRANSFORMER;   -- dbt service user
CREATE ROLE IF NOT EXISTS REPORTER;      -- BI / analysts
GRANT ROLE LOADER      TO ROLE SYSADMIN;
GRANT ROLE TRANSFORMER TO ROLE SYSADMIN;
GRANT ROLE REPORTER    TO ROLE SYSADMIN;

USE ROLE SYSADMIN;
CREATE WAREHOUSE IF NOT EXISTS LOAD_WH
    WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;
CREATE WAREHOUSE IF NOT EXISTS TRANSFORM_WH
    WAREHOUSE_SIZE = 'SMALL'  AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS RAW;
CREATE SCHEMA   IF NOT EXISTS RAW.UM;
CREATE SCHEMA   IF NOT EXISTS RAW.CONTROL;
CREATE DATABASE IF NOT EXISTS ANALYTICS;

-- LOADER: write RAW only
GRANT USAGE ON WAREHOUSE LOAD_WH TO ROLE LOADER;
GRANT USAGE ON DATABASE RAW TO ROLE LOADER;
GRANT USAGE, CREATE TABLE, CREATE STAGE ON SCHEMA RAW.UM TO ROLE LOADER;
GRANT USAGE, CREATE TABLE ON SCHEMA RAW.CONTROL TO ROLE LOADER;

-- TRANSFORMER: read RAW, own ANALYTICS
GRANT USAGE ON WAREHOUSE TRANSFORM_WH TO ROLE TRANSFORMER;
GRANT USAGE ON DATABASE RAW TO ROLE TRANSFORMER;
GRANT USAGE ON SCHEMA RAW.UM TO ROLE TRANSFORMER;
GRANT SELECT ON ALL TABLES IN SCHEMA RAW.UM TO ROLE TRANSFORMER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA RAW.UM TO ROLE TRANSFORMER;
GRANT USAGE, CREATE SCHEMA ON DATABASE ANALYTICS TO ROLE TRANSFORMER;

-- REPORTER: read marts only (granted after dbt creates the schema)
GRANT USAGE ON DATABASE ANALYTICS TO ROLE REPORTER;

-- Service users authenticate with key pairs (public keys from Key Vault)
USE ROLE SECURITYADMIN;
CREATE USER IF NOT EXISTS SVC_ADF_UM
    TYPE = SERVICE DEFAULT_ROLE = LOADER DEFAULT_WAREHOUSE = LOAD_WH
    RSA_PUBLIC_KEY = '<adf-public-key>';
CREATE USER IF NOT EXISTS SVC_DBT_UM
    TYPE = SERVICE DEFAULT_ROLE = TRANSFORMER DEFAULT_WAREHOUSE = TRANSFORM_WH
    RSA_PUBLIC_KEY = '<dbt-public-key>';
GRANT ROLE LOADER      TO USER SVC_ADF_UM;
GRANT ROLE TRANSFORMER TO USER SVC_DBT_UM;
